import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
import { resolve } from 'node:path'

// Pass the installed Playwright entry as an argument; no browser is downloaded.
const { chromium } = await import(pathToFileURL(process.argv[2]).href)
const browser = await chromium.launch({ headless: true, channel: 'msedge' })
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 1000 }, colorScheme: 'light' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const url = pathToFileURL(resolve('artifacts/preview.html')).href
  await page.goto(url)
  await page.getByText('28.42 USD', { exact: true }).waitFor()
  assert.equal(await page.locator('#preview-nav').innerText(), 'OpenAI 用量')
  await page.getByRole('button', { name: '近 7 天', exact: true }).click()
  await page.waitForFunction(() => window.testCalls.some(call => call.range === '7d'))
  await page.getByLabel('项目筛选', { exact: true }).fill('proj_demo')
  await page.getByRole('button', { name: '应用', exact: true }).click()
  await page.waitForFunction(() => window.testCalls.some(call => call.projectId === 'proj_demo'))
  await page.getByRole('button', { name: '刷新数据', exact: true }).click()
  await page.getByRole('button', { name: '刷新数据', exact: true }).waitFor()
  await page.screenshot({ path: 'artifacts/overview.png', fullPage: true })
  const callsBeforeLocale = await page.evaluate(() => window.testCalls.length)
  await page.evaluate(() => window.setTestLocale('en'))
  await page.getByRole('heading', { name: 'Usage and costs', exact: true }).waitFor()
  assert.equal(await page.locator('#preview-nav').innerText(), 'OpenAI Usage')
  assert.equal(await page.getByLabel('Project filter', { exact: true }).inputValue(), 'proj_demo')
  assert.equal(await page.getByRole('button', { name: 'Last 7 days', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.equal(await page.evaluate(() => window.testCalls.length), callsBeforeLocale)
  assert.ok((await page.locator('.oa-status').innerText()).includes('11/13/2026'))
  assert.equal(/[\u3400-\u9fff]/u.test(await page.locator('.oa-panel').innerText()), false)
  assert.equal(await page.locator('#preview-nav').evaluate(el => el.scrollWidth > el.clientWidth), false)
  await page.screenshot({ path: 'artifacts/overview-en.png', fullPage: true })
  await page.evaluate(() => window.setTestLocale('zh'))
  await page.getByRole('heading', { name: '用量与费用', exact: true }).waitFor()
  assert.equal(await page.locator('#preview-nav').innerText(), 'OpenAI 用量')
  await page.goto(url + '?setup')
  await page.getByLabel('Admin API Key', { exact: true }).fill('sk-admin-demo-only')
  await page.getByRole('button', { name: '保存并查询', exact: true }).click()
  await page.getByText('28.42 USD', { exact: true }).waitFor()
  await page.getByRole('button', { name: '配置密钥', exact: true }).click()
  assert.equal(await page.getByLabel('Admin API Key', { exact: true }).inputValue(), '')
  await page.goto(url + '?partial')
  await page.getByText('暂不可用', { exact: true }).waitFor()
  await page.getByText('1,245,800', { exact: true }).waitFor()
  assert.equal(await page.getByText('28.42 USD', { exact: true }).count(), 0)
  await page.screenshot({ path: 'artifacts/partial.png', fullPage: true })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.setViewportSize({ width: 420, height: 900 })
  await page.goto(url + '?setup')
  await page.getByRole('heading', { name: '连接你的 OpenAI 账户' }).waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  await page.screenshot({ path: 'artifacts/setup-dark.png', fullPage: true })

  await page.goto(url + '?lang=en&setup')
  await page.getByRole('heading', { name: 'Connect your OpenAI account' }).waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  await page.getByLabel('Admin API Key', { exact: true }).fill('invalid')
  await page.getByRole('button', { name: 'Save and query', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'Enter an Admin API Key' }).waitFor()
  await page.evaluate(() => window.setTestLocale('zh'))
  await page.getByRole('alert').filter({ hasText: '请填写 Admin API Key' }).waitFor()
  await page.evaluate(() => window.setTestLocale('en'))
  await page.getByLabel('Admin API Key', { exact: true }).fill('sk-admin-demo-only')
  await page.getByRole('button', { name: 'Save and query', exact: true }).click()
  await page.getByText('28.42 USD', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Configure key', exact: true }).click()
  assert.equal(await page.getByLabel('Admin API Key', { exact: true }).inputValue(), '')
  assert.equal(/[\u3400-\u9fff]/u.test(await page.locator('.oa-panel').innerText()), false)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  await page.screenshot({ path: 'artifacts/setup-en-dark.png', fullPage: true })
  await page.goto(url + '?lang=en&partial')
  await page.getByText('Unavailable', { exact: true }).waitFor()
  await page.getByRole('alert').filter({ hasText: 'This key cannot access this data' }).waitFor()
  await page.getByRole('alert').filter({ hasText: 'This account or API does not provide' }).waitFor()
  assert.equal(/[\u3400-\u9fff]/u.test(await page.locator('.oa-panel').innerText()), false)
  await page.goto(url + '?lang=en&error')
  await page.getByText('The admin key is invalid, expired, or revoked. Configure a new Admin API Key.', { exact: true }).waitFor()
  await page.evaluate(() => window.setTestLocale('zh'))
  await page.getByText('管理员密钥无效、已过期或已撤销。请重新配置 Admin API Key。', { exact: true }).waitFor()
  const usesHarnessLocale = await page.evaluate(() => window.usesHarnessLocale)
  await page.evaluate(() => window.disposeTestPlugin())
  assert.equal(await page.locator('.oa-panel').count(), 0)
  assert.deepEqual(errors, [])
  console.log(`UI PASS: Chinese/English, live switching without extra queries, sidebar labels, setup/save/errors, dark/narrow layout, disposal; Harness LocaleRuntime=${usesHarnessLocale}; no browser errors.`)
} finally { await browser.close() }
